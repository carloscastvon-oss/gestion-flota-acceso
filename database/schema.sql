-- Esquema de la aplicacion de gestion de flota y control de acceso.
-- Ejecutar completo en Supabase: SQL Editor > New query > Run.
-- El script es idempotente: se puede volver a ejecutar sin perder datos.

-- ---------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------

create table if not exists vehiculos (
    id                  integer generated by default as identity primary key,
    patente             text not null unique,
    tipo_vehiculo       text not null,
    marca_modelo        text not null,
    anio                integer check (anio between 1950 and 2100),
    kilometraje_actual  integer not null default 0 check (kilometraje_actual >= 0),
    estado_operativo    text not null default 'Operativo'
        check (estado_operativo in ('Operativo', 'Requiere Mantención', 'Crítico'))
);

create table if not exists conductores (
    id               integer generated by default as identity primary key,
    rut              text not null unique,
    nombre_completo  text not null,
    grado_o_cargo    text,
    unidad_destino   text,
    estado           text not null default 'Activo'
        check (estado in ('Activo', 'Inactivo'))
);

create table if not exists autorizaciones (
    id                integer generated by default as identity primary key,
    patente           text not null references vehiculos (patente) on update cascade on delete cascade,
    rut_conductor     text not null references conductores (rut) on update cascade on delete cascade,
    fecha_asignacion  timestamptz not null default now(),
    vigente           boolean not null default true,
    unique (patente, rut_conductor)
);

create table if not exists reportes_estado (
    id                    integer generated by default as identity primary key,
    patente               text not null references vehiculos (patente) on update cascade on delete cascade,
    rut_conductor         text not null references conductores (rut) on update cascade on delete cascade,
    fecha_reporte         timestamptz not null default now(),
    tipo_registro         text not null default 'REPORTE'
        check (tipo_registro in ('ENTRADA', 'SALIDA', 'REPORTE')),
    kilometraje_salida    integer check (kilometraje_salida >= 0),
    nivel_combustible     integer check (nivel_combustible between 0 and 100),
    presion_neumaticos    boolean,
    luces_operativas      boolean,
    estado_frenos         text not null default 'Operativo'
        check (estado_frenos in ('Operativo', 'Con falla')),
    estado_neumaticos     text not null default 'Óptimo'
        check (estado_neumaticos in ('Óptimo', 'Baja presión', 'Baja presión severa')),
    observaciones         text,
    foto_evidencia_url    text,
    -- Parametro critico fuera de norma: falla de frenos o baja presion severa.
    critico               boolean generated always as (
        estado_frenos = 'Con falla' or estado_neumaticos = 'Baja presión severa'
    ) stored
);

create index if not exists idx_autorizaciones_rut on autorizaciones (rut_conductor);
create index if not exists idx_reportes_patente_fecha on reportes_estado (patente, fecha_reporte desc);
create index if not exists idx_reportes_fecha on reportes_estado (fecha_reporte desc);

-- ---------------------------------------------------------------
-- Logica automatizada: al registrar un reporte se actualiza el
-- vehiculo en la tabla maestra.
--   * Parametro critico -> estado_operativo = 'Requiere Mantención'
--     (un vehiculo ya 'Crítico' no se degrada ni se mejora).
--   * El kilometraje del vehiculo avanza al mayor valor informado.
-- ---------------------------------------------------------------

create or replace function aplicar_reporte_a_vehiculo() returns trigger
language plpgsql as $$
begin
    update vehiculos
       set kilometraje_actual = greatest(kilometraje_actual, coalesce(new.kilometraje_salida, 0)),
           estado_operativo = case
               when new.critico and estado_operativo = 'Operativo' then 'Requiere Mantención'
               else estado_operativo
           end
     where patente = new.patente;
    return new;
end;
$$;

drop trigger if exists trg_aplicar_reporte on reportes_estado;
create trigger trg_aplicar_reporte
    after insert on reportes_estado
    for each row execute function aplicar_reporte_a_vehiculo();

-- ---------------------------------------------------------------
-- Seguridad: la aplicacion accede solo desde el servidor de Streamlit
-- con la llave secreta. Con RLS activo y sin politicas, las llaves
-- publicas (anon/authenticated) no pueden leer ni escribir.
-- ---------------------------------------------------------------

alter table vehiculos        enable row level security;
alter table conductores      enable row level security;
alter table autorizaciones   enable row level security;
alter table reportes_estado  enable row level security;

-- ---------------------------------------------------------------
-- Storage: bucket privado de evidencias, maximo 800 KB por imagen.
-- Sin politicas sobre storage.objects, solo la llave secreta accede;
-- la app entrega URLs firmadas y temporales para visualizar las fotos.
-- ---------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('evidencias-vehiculares', 'evidencias-vehiculares', false, 819200,
        array['image/jpeg', 'image/png'])
on conflict (id) do update
    set public = false,
        file_size_limit = 819200,
        allowed_mime_types = array['image/jpeg', 'image/png'];

-- ---------------------------------------------------------------
-- Permisos: los proyectos nuevos de Supabase no otorgan privilegios
-- automaticos sobre 'public'. Solo el rol de la llave secreta accede.
-- ---------------------------------------------------------------

grant usage on schema public to service_role;
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;
